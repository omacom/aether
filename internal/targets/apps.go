type iniSection struct {
	name  string
	lines []string // body lines, header excluded
}

func iniHeader(l string) (string, bool) {
	t := strings.TrimSpace(l)
	if strings.HasPrefix(t, "[") && strings.HasSuffix(t, "]") {
		return t[1 : len(t)-1], true
	}
	return "", false
}

// setINISections sets keys in the named sections of an INI document, keeping
// every other section, key, comment and blank line byte-identical. Missing
// sections are appended and missing keys are added to the end of their
// section; iteration is sorted so output is deterministic.
func setINISections(src string, sections map[string]map[string]string) string {
	var lines []string
	if src != "" {
		lines = strings.Split(strings.TrimSuffix(src, "\n"), "\n")
	}
	names := make([]string, 0, len(sections))
	for n := range sections {
		names = append(names, n)
	}
	sort.Strings(names)

	for _, name := range names {
		keys := make([]string, 0, len(sections[name]))
		for k := range sections[name] {
			keys = append(keys, k)
		}
		sort.Strings(keys)

		start, end := -1, len(lines)
		for i, l := range lines {
			if h, ok := iniHeader(l); ok {
				if start >= 0 {
					end = i
					break
				}
				if h == name {
					start = i
				}
			}
		}
		if start < 0 {
			if len(lines) > 0 && strings.TrimSpace(lines[len(lines)-1]) != "" {
				lines = append(lines, "")
			}
			lines = append(lines, "["+name+"]")
			for _, k := range keys {
				lines = append(lines, k+"="+sections[name][k])
			}
			continue
		}
		pending := map[string]bool{}
		for _, k := range keys {
			pending[k] = true
		}
		for i := start + 1; i < end; i++ {
			k, _, ok := strings.Cut(lines[i], "=")
			k = strings.TrimSpace(k)
			if ok && pending[k] {
				lines[i] = k + "=" + sections[name][k]
				delete(pending, k)
			}
		}
		// New keys go after the last non-blank line of the section.
		at := end
		for at > start+1 && strings.TrimSpace(lines[at-1]) == "" {
			at--
		}
		var add []string
		for _, k := range keys {
			if pending[k] {
				add = append(add, k+"="+sections[name][k])
			}
		}
		lines = append(lines[:at], append(add, lines[at:]...)...)
	}
	return strings.Join(lines, "\n") + "\n"
}

func qtSections(c Context) map[string]map[string]string {
	r := c.Yoz.Roles
	sec := func(bg, alt, fg, inactive, focus, hover string) map[string]string {
		return map[string]string{
			"BackgroundNormal": rgbTriple(bg), "BackgroundAlternate": rgbTriple(alt),
			"ForegroundNormal": rgbTriple(fg), "ForegroundInactive": rgbTriple(inactive),
			"ForegroundActive": rgbTriple(r["accent2"]), "ForegroundLink": rgbTriple(r["accent"]),
			"ForegroundVisited": rgbTriple(r["accent2"]), "ForegroundNegative": rgbTriple(r["danger"]),
			"ForegroundNeutral": rgbTriple(r["warn"]), "ForegroundPositive": rgbTriple(r["ok"]),
			"DecorationFocus": rgbTriple(focus), "DecorationHover": rgbTriple(hover),
		}
	}
	sel := sec(r["accent"], r["accent2"], r["accentInk"], r["accentInk"], r["accent"], r["accent2"])
	// Text drawn on the accent must stay accentInk, not the accent itself.
	for _, k := range []string{"ForegroundActive", "ForegroundLink", "ForegroundVisited"} {
		sel[k] = rgbTriple(r["accentInk"])
	}
	return map[string]map[string]string{
		"Colors:Window":        sec(r["surface"], r["surface2"], r["text"], r["muted"], r["accent"], r["accent2"]),
		"Colors:View":          sec(r["ground"], r["surface"], r["text"], r["muted"], r["accent"], r["accent2"]),
		"Colors:Button":        sec(r["surface2"], r["surface"], r["text"], r["muted"], r["accent"], r["accent2"]),
		"Colors:Selection":     sel,
		"Colors:Tooltip":       sec(r["surface2"], r["surface"], r["text"], r["muted"], r["accent"], r["accent2"]),
		"Colors:Header":        sec(r["surface"], r["surface2"], r["text"], r["muted"], r["accent"], r["accent2"]),
		"Colors:Complementary": sec(r["ground"], r["surface"], r["text"], r["muted"], r["accent"], r["accent2"]),
	}
}

// KF6 apps outside Plasma (Dolphin, Kate, …) ignore kdeglobals' colours and
// the Qt platform theme: KColorSchemeManager applies the scheme named in the
// app's own rc file (UiSettings/ColorScheme). So Aether ships a full .colors
// scheme and selects it for Dolphin.
const qtSchemeName = "Aether"
const qtSchemePath = ".local/share/color-schemes/Aether.colors"

func qtScheme(c Context) (string, error) {
	secs := qtSections(c)
	secs["General"] = map[string]string{"Name": qtSchemeName, "ColorScheme": qtSchemeName}
	secs["KDE"] = map[string]string{"contrast": "4"}
	// Plasma's defaults would wash inactive windows out; keep them as-is.
	secs["ColorEffects:Inactive"] = map[string]string{"Enable": "false", "ChangeSelectionColor": "false"}
	secs["ColorEffects:Disabled"] = map[string]string{
		"ColorAmount": "0", "ColorEffect": "0", "ContrastAmount": "0.65", "ContrastEffect": "1",
		"IntensityAmount": "0.1", "IntensityEffect": "2",
	}
	return "# Generated by Aether — do not edit\n" + setINISections("", secs), nil
}

// qtIconDirs is where icon themes are looked up (tests swap it).
var qtIconDirs = []string{"/usr/share/icons", ".local/share/icons"}

func qtIconTheme(c Context) string {
	icons := "Papirus-Dark"
	if color.HexToHSL(c.Yoz.Roles["ground"]).L > 50 {
		icons = "Papirus-Light"
	}
	for _, d := range qtIconDirs {
		if !filepath.IsAbs(d) {
			d = filepath.Join(c.Home, d)
		}
		if isDir(filepath.Join(d, icons)) {
			return icons
		}
	}
	return ""
}

func qtKdeglobals(c Context, src string) (string, error) {
	secs := qtSections(c)
	// The icon theme is a user choice: only fill it in when unset.
	if _, set := iniValue(src, "Icons", "Theme"); !set {
		if icons := qtIconTheme(c); icons != "" {
			secs["Icons"] = map[string]string{"Theme": icons}
		}
	}
	return setINISections(src, secs), nil
}

// iniValue reports a key's value inside [section].
func iniValue(src, section, key string) (string, bool) {
	in := false
	for _, l := range strings.Split(src, "\n") {
		if h, ok := iniHeader(l); ok {
			in = h == section
			continue
		}
		if k, v, ok := strings.Cut(l, "="); in && ok && strings.TrimSpace(k) == key {
			return strings.TrimSpace(v), true
		}
	}
	return "", false
}

// KItemListView (Dolphin's file view) keeps the palette that existed when it
// was built, before KColorSchemeManager swaps the scheme in. So the startup
// palette must already match: launch Dolphin with QT_QPA_PLATFORMTHEME=qt6ct
// and give qt6ct the same colours. Order is QPalette::ColorRole 0..20:
// WindowText Button Light Midlight Dark Mid Text BrightText ButtonText Base
// Window Shadow Highlight HighlightedText Link LinkVisited AlternateBase NoRole
// ToolTipBase ToolTipText PlaceholderText.
const qt6ctScheme = ".config/qt6ct/colors/aether.conf"

func qt6ctPalette(c Context) (string, error) {
	r := c.Yoz.Roles
	argb := func(hex string) string { return "#ff" + strings.ToLower(noHash(hex)) }
	row := func(fg, hl, hlText string) string {
		cols := []string{
			fg, r["surface2"], r["border"], color.LightenRGB(r["surface2"], 5), r["ground"], r["border"],
			fg, r["text"], fg, r["ground"], r["surface"], "#000000",
			hl, hlText, r["accent"], r["accent2"], r["surface"],
			r["ground"], r["surface2"], r["text"],
		}
		out := make([]string, 0, len(cols)+1)
		for _, h := range cols {
			out = append(out, argb(h))
		}
		out = append(out, "#99"+strings.ToLower(noHash(r["muted"])))
		return strings.Join(out, ", ")
	}
	active := row(r["text"], r["accent"], r["accentInk"])
	return "# Generated by Aether — do not edit\n[ColorScheme]\n" +
		"active_colors=" + active + "\n" +
		"disabled_colors=" + row(r["muted"], r["surface2"], r["muted"]) + "\n" +
		"inactive_colors=" + active + "\n", nil
}

// qt6ctAppearance points qt6ct at the Aether palette, keeping every other
// user setting (style, fonts, dialogs, …).
func qt6ctAppearance(c Context, src string) (string, error) {
	app := map[string]string{
		"custom_palette":    "true",
		"color_scheme_path": filepath.Join(c.Home, qt6ctScheme),
	}
	if _, set := iniValue(src, "Appearance", "icon_theme"); !set {
		if icons := qtIconTheme(c); icons != "" {
			app["icon_theme"] = icons
		}
	}
	return setINISections(src, map[string]map[string]string{"Appearance": app}), nil
}

