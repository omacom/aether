var btopThemeLine = regexp.MustCompile(`(?m)^[ \t]*color_theme[ \t]*=.*$`)

func editBtopConf(_ Context, src string) (string, error) {
	const line = `color_theme = "aether"`
	if btopThemeLine.MatchString(src) {
		return btopThemeLine.ReplaceAllLiteralString(src, line), nil
	}
	if src != "" && !strings.HasSuffix(src, "\n") {
		src += "\n"
	}
	return src + line + "\n", nil
}

