// ---- starship ---------------------------------------------------------------------

const (
	starshipBegin = "# >>> aether palette >>>"
	starshipEnd   = "# <<< aether palette <<<"
	blockMarker   = "\x00aether-block"
)

var (
	tomlHeader  = regexp.MustCompile(`^\s*\[\[?[^\[\]]+\]\]?\s*(#.*)?$`)
	tomlPalette = regexp.MustCompile(`^\s*palette\s*=`)
)

func starshipBlock(c Context) string {
	r := c.Yoz.Roles
	t := c.Yoz.Term
	kv := [][2]string{
		{"bg", r["ground"]}, {"fg", r["text"]}, {"muted", r["muted"]}, {"accent", r["accent"]}, {"accent2", r["accent2"]},
		{"red", t[1]}, {"green", t[2]}, {"yellow", t[3]}, {"blue", t[4]}, {"magenta", t[5]}, {"cyan", t[6]},
	}
	lines := []string{starshipBegin, "[palettes.aether]"}
	for _, p := range kv {
		lines = append(lines, fmt.Sprintf("%s = %q", p[0], p[1]))
	}
	return strings.Join(append(lines, starshipEnd), "\n")
}

func editStarship(c Context, src string) (string, error) {
	var lines []string
	if src != "" {
		lines = strings.Split(strings.TrimSuffix(src, "\n"), "\n")
	}
	// Swap an existing block for a placeholder so everything else is untouched.
	begin, end := -1, -1
	for i, l := range lines {
		switch strings.TrimSpace(l) {
		case starshipBegin:
			begin = i
		case starshipEnd:
			end = i
		}
	}
	if (begin >= 0) != (end >= 0) || end < begin {
		return "", fmt.Errorf("starship.toml: unbalanced aether palette markers")
	}
	if begin >= 0 {
		rest := append([]string{blockMarker}, lines[end+1:]...)
		lines = append(lines[:begin:begin], rest...)
	}

	// Locate the first table header, skipping multi-line string bodies.
	firstTable, palette := -1, -1
	inStr := ""
	for i, l := range lines {
		if inStr == "" {
			if l == blockMarker || tomlHeader.MatchString(l) {
				firstTable = i
				break
			}
			if tomlPalette.MatchString(l) && palette < 0 {
				palette = i
			}
		}
		for _, q := range []string{`"""`, `'''`} {
			if inStr != "" && inStr != q {
				continue
			}
			if strings.Count(l, q)%2 == 1 {
				if inStr == "" {
					inStr = q
				} else {
					inStr = ""
				}
			}
		}
	}
	const pal = `palette = "aether"`
	switch {
	case palette >= 0:
		lines[palette] = pal
	case firstTable >= 0:
		lines = append(lines[:firstTable], append([]string{pal, ""}, lines[firstTable:]...)...)
	default:
		lines = append(lines, pal)
	}

	block := starshipBlock(c)
	placed := false
	for i, l := range lines {
		if l == blockMarker {
			lines[i] = block
			placed = true
		}
	}
	if !placed {
		if len(lines) > 0 && strings.TrimSpace(lines[len(lines)-1]) != "" {
			lines = append(lines, "")
		}
		lines = append(lines, block)
	}
	return strings.Join(lines, "\n") + "\n", nil
}

func starshipTarget() Target {
	return Target{
		ID: "starship", Label: "Starship", Detect: requires("starship"),
		Files: []File{{Path: ".config/starship.toml", Render: editInPlace(".config/starship.toml", editStarship)}},
	}
}

