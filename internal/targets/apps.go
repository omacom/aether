// templateFile renders one embedded template (relative to Context.Templates)
// for app, through Context.Render when set.
func templateFile(name, app string) func(Context) (string, error) {
	return func(c Context) (string, error) {
		if c.Render != nil {
			return c.Render(name, app)
		}
		if c.Templates == nil {
			return "", fmt.Errorf("template %s: no template filesystem", name)
		}
		raw, err := fs.ReadFile(c.Templates, name)
		if err != nil {
			return "", fmt.Errorf("read template %s: %w", name, err)
		}
		return template.ProcessTemplate(string(raw), c.Vars), nil
	}
}

// editInPlace renders a user-owned file by transforming its current content.
// The original is backed up before its first modification.
func editInPlace(rel string, edit func(c Context, src string) (string, error)) func(Context) (string, error) {
	return func(c Context) (string, error) {
		p := filepath.Join(c.Home, rel)
		var src string
		exists := false
		if raw, err := os.ReadFile(p); err == nil {
			src, exists = string(raw), true
		} else if !os.IsNotExist(err) {
			return "", err
		}
		out, err := edit(c, src)
		if err != nil {
			return "", err
		}
		if exists && out != src {
			if err := c.Backups.Save(p); err != nil {
				return "", err
			}
		}
		return out, nil
	}
}

func noHash(hex string) string { return strings.TrimPrefix(hex, "#") }

func isDir(p string) bool {
	st, err := os.Stat(p)
	return err == nil && st.IsDir()
}

func exists(p string) bool {
	_, err := os.Stat(p)
	return err == nil
}

