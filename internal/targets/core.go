func gtkTarget() Target {
	var files []File
	var incs []Include
	var cleanup []string
	for _, v := range []string{"gtk-3.0", "gtk-4.0"} {
		files = append(files, File{Path: ".config/" + v + "/aether-colors.css", Render: renderGTK})
		incs = append(incs, Include{
			Path: ".config/" + v + "/gtk.css", Line: `@import url("aether-colors.css");`,
			Replaces: []string{`@import url("yozakura-colors.css");`},
		})
		cleanup = append(cleanup, ".config/"+v+"/yozakura-colors.css")
	}
	return Target{ID: "gtk", Label: "GTK 3/4", Detect: always, Files: files, Includes: incs, Cleanup: cleanup}
}

