// have reports whether name is on PATH, honouring the injectable Context.Have.
func (c Context) have(name string) bool {
	if c.Have != nil {
		return c.Have(name)
	}
	_, err := exec.LookPath(name)
	return err == nil
}

func requires(bin string) func(Context) bool {
	return func(c Context) bool { return c.have(bin) }
}

func always(Context) bool { return true }

// pyFloat formats like Python's str(float): shortest repr, ".0" for integers.
func pyFloat(f float64) string {
	s := strconv.FormatFloat(f, 'f', -1, 64)
	if !strings.Contains(s, ".") {
		s += ".0"
	}
	return s
}

func round2(f float64) float64 { return math.Round(f*100) / 100 }

func rgbCSS(hex string, alpha float64) string {
	c := color.HexToRGB(hex)
	return fmt.Sprintf("rgba(%d, %d, %d, %s)", int(c.R+0.5), int(c.G+0.5), int(c.B+0.5), pyFloat(alpha))
}

func rgbTriple(hex string) string {
	c := color.HexToRGB(hex)
	return fmt.Sprintf("%d, %d, %d", int(c.R+0.5), int(c.G+0.5), int(c.B+0.5))
}

// hyprRGBA formats "rgba(rrggbbaa)" for Hyprland.
func hyprRGBA(hex string, alpha float64) string {
	return fmt.Sprintf("rgba(%s%02x)", strings.TrimPrefix(hex, "#"), int(math.Round(alpha*255)))
}

// ---- yozakura ---------------------------------------------------------------------

type yozakuraFile struct {
	Name      string         `json:"name"`
	Glass     float64        `json:"glass"`
	Clock     yozakura.Clock `json:"clock"`
	Ground    string         `json:"ground"`
	Surface   string         `json:"surface"`
	Surface2  string         `json:"surface2"`
	Border    string         `json:"border"`
	Accent    string         `json:"accent"`
	Accent2   string         `json:"accent2"`
	Info      string         `json:"info"`
	Danger    string         `json:"danger"`
	Ok        string         `json:"ok"`
	Warn      string         `json:"warn"`
	Text      string         `json:"text"`
	Muted     string         `json:"muted"`
	AccentInk string         `json:"accentInk"`
	Term      []string       `json:"term"`
	ID        string         `json:"id"`
	Wallpaper string         `json:"wallpaper"`
}

func renderYozakura(c Context) (string, error) {
	r := c.Yoz.Roles
	f := yozakuraFile{
		Name: c.Name, Glass: c.Yoz.Glass, Clock: c.Yoz.Clock,
		Ground: r["ground"], Surface: r["surface"], Surface2: r["surface2"], Border: r["border"],
		Accent: r["accent"], Accent2: r["accent2"], Info: r["info"], Danger: r["danger"],
		Ok: r["ok"], Warn: r["warn"], Text: r["text"], Muted: r["muted"], AccentInk: r["accentInk"],
		Term: append([]string{}, c.Yoz.Term[:8]...), ID: c.ID, Wallpaper: c.Wallpaper,
	}
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", " ")
	if err := enc.Encode(f); err != nil {
		return "", err
	}
	return strings.TrimSuffix(buf.String(), "\n"), nil
}

// ---- hyprland ---------------------------------------------------------------------

func renderHyprland(c Context) (string, error) {
	r := c.Yoz.Roles
	return fmt.Sprintf("-- Generated by Aether (%s). Do not edit.\n"+
		"hl.config({\n    general = {\n        col = {\n"+
		"            active_border   = { colors = {\"%s\", \"%s\"}, angle = 45 },\n"+
		"            inactive_border = \"%s\",\n"+
		"        },\n    },\n})\n",
		c.Name, hyprRGBA(r["accent"], 0.93), hyprRGBA(r["accent2"], 0.93), hyprRGBA(r["border"], 0.67)), nil
}

const hyprColorsPath = ".config/hypr/aether-colors.lua"

func hyprReload(c Context) []string {
	p := filepath.Join(c.Home, hyprColorsPath)
	p = strings.NewReplacer(`\`, `\\`, `'`, `\'`).Replace(p)
	return []string{"hyprctl", "eval", "dofile('" + p + "')"}
}

// ---- kitty ------------------------------------------------------------------------

// reduceMotion mirrors Theme.qml: the flag file exists, or GNOME
// enable-animations is off.
func reduceMotion(c Context) bool {
	if _, err := os.Stat(filepath.Join(c.Home, ".local/state/yozakura/reduce-motion")); err == nil {
		return true
	}
	if c.Run == nil {
		return false
	}
	out, _ := c.Run("gsettings", "get", "org.gnome.desktop.interface", "enable-animations")
	return strings.TrimSpace(out) == "false"
}

func renderKitty(c Context) (string, error) {
	r := c.Yoz.Roles
	trail := "cursor_trail 120"
	if reduceMotion(c) {
		trail = "cursor_trail 0"
	}
	lines := []string{
		fmt.Sprintf("# Generated by Aether (%s). Do not edit.", c.Name),
		"foreground " + r["text"], "background " + r["ground"],
		"selection_foreground " + r["accentInk"], "selection_background " + r["accent"],
		"cursor " + r["accent"], "cursor_text_color " + r["accentInk"],
		"url_color " + r["info"],
		"active_border_color " + r["accent"], "inactive_border_color " + r["border"],
		"active_tab_foreground " + r["accentInk"], "active_tab_background " + r["accent"],
		"inactive_tab_foreground " + r["muted"], "inactive_tab_background " + r["surface"],
		"tab_bar_background " + r["ground"], "tab_bar_margin_color " + r["ground"],
		fmt.Sprintf("background_opacity %.2f", math.Max(0.92, c.Yoz.Glass)),
		"cursor_trail_color " + r["accent"],
		trail,
		"visual_bell_color " + r["danger"], "bell_border_color " + r["danger"],
		"scrollbar_handle_color " + r["muted"], "scrollbar_track_color " + r["surface"],
		"mark1_background " + r["accent"], "mark2_background " + r["warn"], "mark3_background " + r["info"],
	}
	for i, v := range c.Yoz.Term {
		lines = append(lines, fmt.Sprintf("color%d %s", i, v))
	}
	return strings.Join(lines, "\n") + "\n", nil
}

// ---- gtk --------------------------------------------------------------------------

func renderGTK(c Context) (string, error) {
	r := c.Yoz.Roles
	named := [][2]string{
		// libadwaita (GTK4)
		{"accent_color", r["accent"]}, {"accent_bg_color", r["accent"]}, {"accent_fg_color", r["accentInk"]},
		{"destructive_color", r["danger"]}, {"destructive_bg_color", r["danger"]}, {"destructive_fg_color", r["accentInk"]},
		{"success_color", r["ok"]}, {"warning_color", r["warn"]}, {"error_color", r["danger"]},
		{"window_bg_color", r["surface"]}, {"window_fg_color", r["text"]},
		{"view_bg_color", r["ground"]}, {"view_fg_color", r["text"]},
		{"headerbar_bg_color", r["surface"]}, {"headerbar_fg_color", r["text"]},
		{"headerbar_backdrop_color", r["ground"]},
		{"sidebar_bg_color", r["ground"]}, {"sidebar_fg_color", r["text"]},
		{"secondary_sidebar_bg_color", r["surface"]}, {"secondary_sidebar_fg_color", r["text"]},
		{"card_bg_color", r["surface2"]}, {"card_fg_color", r["text"]},
		{"dialog_bg_color", r["surface"]}, {"dialog_fg_color", r["text"]},
		{"popover_bg_color", r["surface2"]}, {"popover_fg_color", r["text"]},
		{"thumbnail_bg_color", r["surface2"]}, {"thumbnail_fg_color", r["text"]},
		// Adwaita (GTK3)
		{"theme_bg_color", r["surface"]}, {"theme_fg_color", r["text"]},
		{"theme_base_color", r["ground"]}, {"theme_text_color", r["text"]},
		{"theme_selected_bg_color", r["accent"]}, {"theme_selected_fg_color", r["accentInk"]},
		{"insensitive_fg_color", r["muted"]}, {"borders", r["border"]},
	}
	lines := make([]string, len(named))
	for i, kv := range named {
		lines[i] = fmt.Sprintf("@define-color %s %s;", kv[0], kv[1])
	}
	return fmt.Sprintf("/* Generated by Aether (%s). Do not edit. */\n%s\n", c.Name, strings.Join(lines, "\n")), nil
}

// ---- swaync -----------------------------------------------------------------------

func renderSwaync(c Context) (string, error) {
	r := c.Yoz.Roles
	g := c.Yoz.Glass
	v := [][2]string{
		{"cc-bg", rgbCSS(r["ground"], round2(g-0.05))},
		{"noti-border-color", rgbCSS(r["accent"], 0.25)},
		{"noti-bg", rgbTriple(r["surface"])},
		{"noti-bg-alpha", pyFloat(g)},
		{"noti-bg-darker", r["ground"]},
		{"noti-bg-hover", r["surface2"]},
		{"noti-bg-focus", rgbCSS(r["surface2"], 0.6)},
		{"noti-close-bg", r["surface2"]},
		{"noti-close-bg-hover", r["border"]},
		{"text-color", r["text"]},
		{"text-color-disabled", r["muted"]},
		{"bg-selected", r["accent"]},
	}
	var root, legacy []string
	for _, kv := range v {
		root = append(root, fmt.Sprintf("  --%s: %s;", kv[0], kv[1]))
		if kv[0] != "noti-bg" && kv[0] != "noti-bg-alpha" {
			legacy = append(legacy, fmt.Sprintf("@define-color %s %s;", kv[0], kv[1]))
		}
	}
	return fmt.Sprintf("/* Generated by Aether (%s). Do not edit. */\n:root {\n%s\n}\n%s\n",
		c.Name, strings.Join(root, "\n"), strings.Join(legacy, "\n")), nil
}

