func yozakuraTarget() Target {
	return Target{
		ID: "yozakura", Label: "Yozakura shell", Detect: always,
		Files: []File{{Path: ".local/state/yozakura/theme.json", Render: renderYozakura}},
	}
}

func hyprlandTarget() Target {
	return Target{
		ID: "hyprland", Label: "Hyprland", Detect: requires("hyprctl"),
		Files: []File{{Path: hyprColorsPath, Render: renderHyprland}},
		Includes: []Include{{
			Path:   ".config/hypr/hyprland.lua",
			Line:   `dofile(os.getenv("HOME") .. "/.config/hypr/aether-colors.lua")`,
			Append: true,
		}},
		Reload:       hyprReload,
		AlwaysReload: true,
		Cleanup:      []string{".config/hypr/yozakura-colors.lua"},
	}
}

